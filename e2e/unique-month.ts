import { test } from "@playwright/test";

// テスト用の月("YYYY-MM")。同じ DB を desktop / mobile の複数ワーカーで共有するので、
// 月が重なると他のテストが作った練習を数えてしまい、件数や文言の検証が落ちる。
//
// 以前は 2031〜2090 年からランダムに選んでいたが、1回の実行で 19 か所 × 2 プロジェクト =
// 最大 38 回引くのに対し候補は 720 通りしかなく、誕生日のパラドックスで
// **1回の実行あたり平均 1 件ほど衝突していた**(Issue #175)。
// ワーカーごとに使う年の帯を分け、同じワーカー内では呼ぶたびに次の年へ進めて、
// 1回の実行のなかで必ず別の年になるようにする。

/** ワーカー1つに割り当てる年数。1ワーカーが使う回数より十分多くとる */
const YEARS_PER_WORKER = 12;

let used = 0;

/**
 * このテスト実行のなかで他と重ならない月("YYYY-MM")。シードの月とも重ならない。
 *
 * **テストごとに別の「年」を割り当て、月は 6 月に固定する。** 前の月・次の月へ動いて
 * 「練習はまだ登録されていません」を確かめるテストがあるので、隣の月まで空けておく必要がある
 * (年をまたいで連番にすると、隣の月を別のテストが使ってしまう)
 */
export function uniqueMonth(): string {
  const year = 2031 + test.info().workerIndex * YEARS_PER_WORKER + used;
  used += 1;
  return `${year}-06`;
}
